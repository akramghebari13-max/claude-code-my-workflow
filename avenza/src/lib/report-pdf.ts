import type { buildBalanceSheet, buildPnl } from "./reports";

type Pnl = ReturnType<typeof buildPnl>;
type Bs = ReturnType<typeof buildBalanceSheet>;
export type ReportPdfInput = {
  businessName: string; periodLabel: string; from: string; to: string; isLtd: boolean;
  pnl: Pnl; bs: Bs; taxRows: [string, number][];
};

const money = (p: number) => (p < 0 ? "(" : "") + "£" + (Math.abs(p) / 100).toLocaleString("en-GB", { minimumFractionDigits: 2, maximumFractionDigits: 2 }) + (p < 0 ? ")" : "");
const ukDate = (iso: string) => new Date(iso + "T12:00:00Z").toLocaleDateString("en-GB", { timeZone: "UTC" });

/** Builds the reports PDF from figures (not a screenshot), so it works on phones too. */
export async function buildReportPdf(r: ReportPdfInput): Promise<Blob> {
  const { jsPDF } = await import("jspdf");
  const { default: autoTable } = await import("jspdf-autotable");
  const doc = new jsPDF({ unit: "mm", format: "a4" });
  const green: [number, number, number] = [31, 77, 58];
  doc.setFont("helvetica", "bold"); doc.setFontSize(18); doc.text(r.businessName, 14, 18);
  doc.setFont("helvetica", "normal"); doc.setFontSize(10);
  doc.text(`${r.periodLabel}  ·  ${ukDate(r.from)} – ${ukDate(r.to)}`, 14, 25);
  let y = 32;
  const section = (title: string, rows: [string, number, boolean?][]) => {
    autoTable(doc, {
      startY: y, head: [[title, ""]], body: rows.map(([l, v]) => [l, money(v)]),
      theme: "plain", headStyles: { fillColor: green, textColor: 255, fontStyle: "bold" },
      columnStyles: { 1: { halign: "right", font: "courier" } },
      didParseCell: (d) => { if (d.section === "body" && rows[d.row.index]?.[2]) d.cell.styles.fontStyle = "bold"; },
      margin: { left: 14, right: 14 },
    });
    y = (doc as unknown as { lastAutoTable: { finalY: number } }).lastAutoTable.finalY + 6;
  };
  const named = (x: { code: string; name: string; amount: number }[]) => x.map((a) => [`${a.code} ${a.name}`.trim(), a.amount] as [string, number]);
  section("Profit and loss", [
    ...named(r.pnl.income), ["Total income", r.pnl.totalIncome, true],
    ...named(r.pnl.expenses), ["Total expenses", r.pnl.totalExpenses, true],
    [r.pnl.profit >= 0 ? "Net profit" : "Net loss", r.pnl.profit, true],
  ]);
  section(`Balance sheet as at ${ukDate(r.to)}`, [
    ...named(r.bs.assets), ["Total assets", r.bs.totalAssets, true],
    ...named(r.bs.liabilities), ["Total liabilities", r.bs.totalLiabilities, true],
    ...named(r.bs.equity), ["Profit to date", r.bs.retainedProfit],
    [r.isLtd ? "Total capital & reserves" : "Total owner's capital", r.bs.totalEquity, true],
    ["Net assets", r.bs.totalAssets - r.bs.totalLiabilities, true],
  ]);
  section("Tax estimate", r.taxRows.map(([l, v], i) => [l, v, i === r.taxRows.length - 1] as [string, number, boolean]));
  doc.setFontSize(8); doc.setTextColor(110);
  doc.text(doc.splitTextToSize("Tax figures are estimates only and not tax advice. " + (r.isLtd
    ? "Corporation Tax: 19% up to £50,000, 25% from £250,000, marginal relief between; before capital allowances and adjustments."
    : "Income Tax and Class 4 NI assume no other income and England, Wales & NI bands."), 182), 14, y + 2);
  doc.text(`Generated by AVENZA on ${new Date().toLocaleDateString("en-GB", { timeZone: "Europe/London" })}`, 14, 290);
  return doc.output("blob");
}

export function downloadBlob(blob: Blob, filename: string) {
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a"); a.href = url; a.download = filename;
  document.body.appendChild(a); a.click(); a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 30_000);
}

/** Phones get the share sheet ("Save to Files"); desktops download. */
export async function deliverFile(blob: Blob, filename: string) {
  const file = new File([blob], filename, { type: blob.type });
  const touch = matchMedia("(pointer: coarse)").matches;
  if (touch && navigator.canShare?.({ files: [file] })) {
    try { await navigator.share({ files: [file], title: filename }); return; }
    catch (e) { if ((e as DOMException).name === "AbortError") return; }
  }
  downloadBlob(blob, filename);
}
